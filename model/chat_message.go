package model

import (
	"time"

	"github.com/google/uuid"
)

// ChatMessage is one text message of a group conversation, stored so the AI
// fallback can see what the group talked about. IsBot marks the bot's own AI
// replies.
type ChatMessage struct {
	ID           uuid.UUID
	ChatJID      string
	MessageID    string // WhatsApp message ID; generated by the store when empty
	SenderJID    string
	SenderAltJID string // Alternate address of the sender (LID vs phone), may be empty
	PushName     string
	Body         string
	IsBot        bool
	CreatedAt    time.Time
}
